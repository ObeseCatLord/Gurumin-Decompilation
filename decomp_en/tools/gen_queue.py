"""gen_queue.py : write decomp_en/QUEUE.md, the EN work queue, from jp_en_map.tsv, open.tsv and the EN report.

Order (HANDOFF "Standing instructions"):
  1. walls to retry (open.tsv, status open)
  2. EN functions whose JP twin is already matched: the JP source is the draft (tools/port_jp.py), smallest first
  3. EN functions mapped to an unmatched JP function, smallest first
  4. EN-only functions (launcher, Steam, unknown), smallest first
Matched state comes from progress/en/report.json, so run build_all.py --report first. Finished items drop out.
It first rebuilds jp_en_map.tsv (map_jp_to_en.py, about 12 s) so new JP matches and classify.tsv changes show up;
--no-map keeps the current map.
"""
import csv, json, os, re, sys

from enimg import EN, REPORT


def main():
    if "--no-map" not in sys.argv:
        import map_jp_to_en
        map_jp_to_en.main()
    rows = list(csv.DictReader(open(os.path.join(EN, "jp_en_map.tsv"), encoding="utf-8"), delimiter="\t"))
    percent = {}
    if os.path.exists(REPORT):
        for unit in json.load(open(REPORT, encoding="utf-8"))["units"]:
            if unit["name"] == "en/unmatched":
                continue
            for f in unit["functions"]:
                percent["%08x" % int(f["metadata"]["virtual_address"])] = (f["fuzzy_match_percent"], unit["name"])
    walls = {}
    path = os.path.join(EN, "open.tsv")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 3 and re.match(r"^00[0-9a-f]{6}$", parts[0]):
                walls[parts[0]] = (parts[1], parts[2])
    done = {a for a, (p, _) in percent.items() if p >= 100}
    todo = [r for r in rows if r["en_address"] not in done and r["en_address"] not in walls]

    def size(r):
        return int(r["en_size"])

    out = ["# EN work queue", "",
           "Generated by `decomp_en/tools/gen_queue.py` from jp_en_map.tsv, open.tsv and progress/en/report.json.",
           "Re-run after each batch (finished items drop out). Per function: `python tools/port_jp.py <address>` prints",
           "the JP twin's matched source, the EN callees with their JP names and the EN disassembly (`--brief` makes a",
           "subagent brief). Low-confidence map rows: check the twin before porting.", ""]
    retry = [(a, s, r) for a, (s, r) in sorted(walls.items()) if a not in done and s == "open"]
    out += ["## 1. Walls to retry (%d)" % len(retry), ""]
    out += ["- [ ] `%s` — %s" % (a, r) for a, s, r in retry]

    def section(title, sel, show_jp=True):
        sel = sorted(sel, key=lambda r: (size(r), r["en_address"]))
        lines = ["", "## %s (%d functions, %d bytes)" % (title, len(sel), sum(size(r) for r in sel)), ""]
        for r in sel:
            if show_jp:
                where = r["jp_status"].split(":", 1)[1] if r["jp_status"].startswith("matched:") else ""
                lines.append("- [ ] `%s` %s bytes <- %s `%s` %s%s (%s %s)" % (
                    r["en_address"], r["en_size"], r["jp_module"], r["jp_address"], r["jp_name"],
                    " [decomp/src/%s]" % where if where else "", r["level"], r["confidence"]))
            else:
                lines.append("- [ ] `%s` %s bytes (%s)" % (r["en_address"], r["en_size"], r["evidence"]))
        return lines

    out += section("2. JP twin matched: port the JP source", [r for r in todo if r["jp_status"].startswith("matched:")])
    out += section("3. JP twin not matched yet", [r for r in todo if r["jp_module"] != "-" and not r["jp_status"].startswith("matched:")])
    out += section("4. EN-only (no JP twin found)", [r for r in todo if r["jp_module"] == "-"], show_jp=False)
    with open(os.path.join(EN, "QUEUE.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("queue: %d walls, %d with a matched JP twin, %d mapped to unmatched JP, %d EN-only" % (
        len(retry), sum(1 for r in todo if r["jp_status"].startswith("matched:")),
        sum(1 for r in todo if r["jp_module"] != "-" and not r["jp_status"].startswith("matched:")),
        sum(1 for r in todo if r["jp_module"] == "-")))


if __name__ == "__main__":
    main()
