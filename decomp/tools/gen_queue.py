"""gen_queue.py : write decomp/QUEUE.md, the work queue, from the project state.

Sections: walls to retry (open.tsv), unmatched functions by size band (decompile), and naming tasks (functions
without a readable name in symbols.tsv). Matched state comes from progress/jp/report.json, so run
build_all.py --report first. Re-run after each batch; finished items drop out.
"""
import csv, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(ROOT)


def load():
    funcs = {r["address"]: r for r in csv.DictReader(open(os.path.join(ROOT, "triage.tsv")), delimiter="\t")
             if r["address"] < "101b2000"}
    report = json.load(open(os.path.join(REPO, "progress", "jp", "report.json"), encoding="utf-8"))
    percent = {}
    for unit in report["units"]:
        if unit["name"] == "app/unmatched":
            continue
        for f in unit["functions"]:
            percent["%08x" % int(f["metadata"]["virtual_address"])] = (f["fuzzy_match_percent"], unit["name"])
    walls = {}
    for line in open(os.path.join(ROOT, "open.tsv"), encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) >= 3 and re.match(r"^10[0-9a-f]{6}$", parts[0]):
            walls[parts[0]] = (parts[1], parts[2])
    named = {}
    for line in open(os.path.join(REPO, "symbols.tsv"), encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) >= 2 and re.match(r"^10[0-9a-f]{6}$", parts[0]):
            named[parts[0]] = parts[1]
    return funcs, percent, walls, named


def main():
    funcs, percent, walls, named = load()
    matched = {a for a, (p, _) in percent.items() if p >= 100}
    out = ["# Work queue", "",
           "Generated by `decomp/tools/gen_queue.py` from triage.tsv, open.tsv, symbols.tsv and the progress report.",
           "Work top to bottom inside each section; re-run the generator after a batch (finished items drop out).", "",
           "Per function: read `tools/fn.py` / `tools/asm.py`, write the source in the matching `src/*.cpp`, build, iterate",
           "with `tools/variants.py` and `tools/sbs.py`; after about five failed spellings record it in `open.tsv` and move on.",
           "Give it a readable name in `symbols.tsv` (and `obj_symbols.tsv` for class methods) once its role is clear.", ""]

    retry = [(a, s, r) for a, (s, r) in sorted(walls.items()) if a not in matched and s == "open"]
    out += ["## 1. Walls to retry (%d)" % len(retry), "",
            "Reasons written before the switch to cl 13.00 describe VS2003 behaviour; retry with the plainest source first.", ""]
    out += ["- [ ] `%s` %s — %s" % (a, funcs.get(a, {}).get("size", "?"), r) for a, s, r in retry]

    todo = [r for a, r in sorted(funcs.items()) if a not in percent and a not in walls]
    bands = [("2. Small functions (30-250 bytes)", 30, 250), ("3. Medium functions (251-800 bytes)", 251, 800),
             ("4. Large functions (801-3000 bytes)", 801, 3000), ("5. Very large functions (over 3000 bytes)", 3001, 10 ** 9)]
    for title, lo, hi in bands:
        rows = sorted([r for r in todo if lo <= int(r["size"]) <= hi], key=lambda r: (int(r["size"]), r["address"]))
        out += ["", "## %s (%d)" % (title, len(rows)), ""]
        for r in rows:
            name = named.get(r["address"], "")
            tags = []
            if r["fp"] != "0":
                tags.append("float")
            if r["loops"] != "0":
                tags.append("loops %s" % r["loops"])
            if r["calls"] != "0":
                tags.append("calls %s" % r["calls"])
            out.append("- [ ] `%s` %s bytes%s%s" % (r["address"], r["size"], " " + name if name else "",
                                                   " (" + ", ".join(tags) + ")" if tags else ""))

    unnamed = sorted(a for a in matched if a not in named)
    out += ["", "## 6. Naming: matched functions without a readable name (%d)" % len(unnamed), "",
            "Read the matched source and its callers, then add `address<TAB>Name<TAB>evidence` to `symbols.tsv`.", ""]
    for a in unnamed:
        out.append("- [ ] `%s` %s bytes (%s)" % (a, funcs[a]["size"], percent[a][1].replace("app/", "src/") + ".cpp"))

    missing = []
    for fn in sorted(os.listdir(os.path.join(ROOT, "src"))):
        if not fn.endswith(".cpp"):
            continue
        lines = open(os.path.join(ROOT, "src", fn), encoding="utf-8", errors="replace").read().splitlines()
        total = bare = 0
        for i in range(len(lines) - 1):
            if lines[i + 1] == "{" and re.match(r"^[A-Za-z_].*\)( const)?$", lines[i]) and not lines[i].startswith(("struct", "class")):
                total += 1
                if i == 0 or not lines[i - 1].lstrip().startswith("//"):
                    bare += 1
        header = lines[0].startswith("//")
        if bare or not header:
            missing.append((fn, bare, total, header))
    out += ["", "## 7. Comment pass (%d files)" % len(missing), "",
            "Every function gets a comment saying what it does, who calls it and what its fields/constants mean; every",
            "file gets a header comment. Comments never change the compiled bytes (tools/annotate.py helps).", ""]
    for fn, bare, total, header in missing:
        out.append("- [ ] `src/%s`: %d of %d functions without a comment%s" % (fn, bare, total, "" if header else ", no header"))

    out += ["", "## 8. Structures and globals", "",
            "- [ ] Merge the per-file copies of `Matrix4`, `TextureObject`, `GameFile`, `ItemInfo` into shared headers in `include/`.",
            "- [ ] Name the CharSlot / ActorSlot / CharState / Character fields used by matched code (include/world.h).",
            "- [ ] Name the Game texture and state fields (include/game.h) from LoadMenuTextures and the draw helpers.",
            "- [ ] Readers of the costume id 0x10c655f0: sort each into look or ability (docs/ROADMAP.md, transmog).",
            "- [ ] Text drawing path (font 0x101455d0, glyph renderer near 0x10145380): name every function (ROADMAP: Unicode font)."]
    with open(os.path.join(ROOT, "QUEUE.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("queue: %d walls, %d to decompile, %d to name" % (len(retry), len(todo), len(unnamed)))


if __name__ == "__main__":
    main()
